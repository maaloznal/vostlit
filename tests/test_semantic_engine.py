# ---------- EvidenceLinker + Synthesis ----------
def test_linker_groups_by_identification(tmp_db):
    _seed_corpus_for_reader(tmp_db)
    eng = ResearchEngine(tmp_db)
    # seed a second doc with a different form but same identification
    d2 = DocumentIn(
        canonical_url="https://www.vostlit.info/Texts/Dokumenty/Kavkaz/VI/Y/text.htm",
        title="Хроника 2", region="Дагестан", original_creation_date="1500",
        extracted_text="Хадар — сел. Кадар, Буйнакский район.",
        sections=[SectionIn(section_type="note", text="Хадар — сел. Кадар, Буйнакский район.", sequence_number=1)],
    )
    store.upsert_document(tmp_db, d2)
    result = eng.research("Гадар")
    # both forms should group under "Кадар" identification
    findings = result["findings"]
    assert len(findings) >= 1
    # the editorial_identification finding should have >=2 independent witnesses
    id_findings = [f for f in findings if f["evidence_type"] == "editorial_identification"]
    if id_findings:
        assert id_findings[0]["independent_witnesses"] >= 2


